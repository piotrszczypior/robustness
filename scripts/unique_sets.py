from itertools import chain

def get_exclusive_values(lists, n=5):
    all_sets = [set(lst) for lst in lists]
    result = []
    for i, s in enumerate(all_sets):
        others = set(chain.from_iterable(all_sets[j] for j in range(len(all_sets)) if j != i))
        exclusive = list(s - others)
        result.append(exclusive[:n] if len(exclusive) >= n else exclusive)
    return result


